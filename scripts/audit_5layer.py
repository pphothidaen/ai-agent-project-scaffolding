#!/usr/bin/env python3
"""
Audit a project against the 12-item 5-layer agent architecture checklist.

Usage:
    python scripts/audit_5layer.py [project_path] [--json] [--freshness]

Scores 0-12. Evidence-based: empty/stale/placeholder files score 0.
Freshness SLA: re-audit at least every 30 days; --freshness checks
.audit_timestamp in the project root and warns if stale.
Runnable from any directory.
"""
import argparse
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timedelta
from pathlib import Path

PLACEHOLDER_MARKERS = [
    "PROJECT_NAME",
    "TODO",
    "FIXME",
    "your-project",
    "lorem ipsum",
]

AUTO_GENERATED_MARKERS = [
    "auto-generated",
    "autogenerated",
    "generated by",
    "do not edit",
    "this file was generated",
]

SELF_CERT_MARKERS = [
    "self-certif",
    "self certif",
    "model certif",
    "certified by the model",
    "approved by the model",
]


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return ""


def is_substantive(text: str, min_chars: int = 40) -> bool:
    stripped = text.strip()
    if len(stripped) < min_chars:
        return False
    # Reject files that are only placeholders
    lower = stripped.lower()
    placeholder_hits = sum(1 for m in PLACEHOLDER_MARKERS if m.lower() in lower)
    if placeholder_hits >= 3 and len(stripped) < 200:
        return False
    return True


def check_agents_md(root: Path):
    p = root / "AGENTS.md"
    if not p.is_file():
        return False, "AGENTS.md not found"
    text = read_text(p)
    lines = text.splitlines()
    if not is_substantive(text, 20):
        return False, "AGENTS.md empty or placeholder-only"
    if len(lines) > 120:
        return False, f"AGENTS.md too long ({len(lines)} lines; want <= ~100)"
    # pointer-based: should reference docs/ or .agents/
    pointer = bool(re.search(r"docs/|\.agents/|adr", text, re.I))
    if not pointer:
        return False, "AGENTS.md not pointer-based (no references to docs/.agents/adr)"
    # human-written: no auto-generated markers
    lower = text.lower()
    if any(m in lower for m in AUTO_GENERATED_MARKERS):
        return False, "AGENTS.md appears auto-generated"
    return True, f"AGENTS.md present, {len(lines)} lines, pointer-based"


def check_rules(root: Path):
    d = root / ".agents" / "rules"
    if not d.is_dir():
        return False, ".agents/rules/ not found"
    md_files = sorted(d.glob("*.md"))
    if not md_files:
        return False, ".agents/rules/ has no .md files"
    numbered = [f for f in md_files if re.match(r"^\d+[-_].*\.md$", f.name)]
    named = [f for f in md_files if re.search(r"intake|developer|reviewer", f.name, re.I)]
    accepted = numbered or named
    if not accepted:
        # accept any non-empty convention? require at least one substantive file
        accepted = md_files
    substantive = [f for f in accepted if is_substantive(read_text(f), 20)]
    if not substantive:
        return False, ".agents/rules/ files empty or placeholder-only"
    detail = f"{len(substantive)} substantive rule file(s)"
    if numbered:
        detail += f" (numbered: {', '.join(f.name for f in numbered)})"
    elif named:
        detail += f" (named: {', '.join(f.name for f in named)})"
    return True, detail


def check_project_md(root: Path):
    p = root / "docs" / "PROJECT.md"
    if not p.is_file():
        return False, "docs/PROJECT.md not found"
    text = read_text(p)
    if not is_substantive(text, 40):
        return False, "docs/PROJECT.md empty or placeholder-only"
    lower = text.lower()
    if not ("architect" in lower or "tech stack" in lower or "technology" in lower or "stack" in lower):
        return False, "docs/PROJECT.md lacks architecture/tech stack content"
    return True, "docs/PROJECT.md documents architecture/tech stack"


def check_tasks_md(root: Path):
    p = root / "docs" / "TASKS.md"
    if not p.is_file():
        return False, "docs/TASKS.md not found"
    text = read_text(p)
    if not is_substantive(text, 40):
        return False, "docs/TASKS.md empty or placeholder-only"
    lower = text.lower()
    ok = all(k in lower for k in ["backlog", "in progress", "completed"])
    if not ok:
        return False, "docs/TASKS.md missing Backlog/In Progress/Completed sections"
    return True, "docs/TASKS.md tracks Backlog/In Progress/Completed"


def check_adr(root: Path):
    d = root / "docs" / "adr"
    if not d.is_dir():
        return False, "docs/adr/ not found"
    adrs = [f for f in d.glob("*.md") if f.name.lower() not in ("readme.md",)]
    substantive = [f for f in adrs if is_substantive(read_text(f), 20)]
    if not substantive:
        return False, "docs/adr/ has no substantive ADR"
    return True, f"{len(substantive)} ADR(s) present"


MCP_ALIASES = [".mcp.json", "mcp.json", "claude_desktop_config.json"]


def _flatten(obj, prefix=""):
    out = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            out.append((f"{prefix}.{k}" if prefix else k, v))
            out.extend(_flatten(v, f"{prefix}.{k}" if prefix else k))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            out.extend(_flatten(v, f"{prefix}[{i}]"))
    else:
        out.append((prefix, obj))
    return out


def check_mcp(root: Path):
    found = None
    for name in MCP_ALIASES:
        p = root / name
        if p.is_file():
            found = p
            break
    # also check .claude/
    if found is None:
        for name in MCP_ALIASES:
            p = root / ".claude" / name
            if p.is_file():
                found = p
                break
    if found is None:
        return False, "MCP config not found (.mcp.json/mcp.json/claude_desktop_config.json)"
    text = read_text(found)
    try:
        data = json.loads(text)
    except Exception:
        return False, f"{found.name} is not valid JSON"
    if not isinstance(data, (dict, list)) or data in ({}, []):
        return False, f"{found.name} is empty"
    flat = _flatten(data)
    restrict_keys = [k for k, v in flat if isinstance(k, str) and re.search(r"allow|restrict|root|path", k, re.I)]
    path_values = [v for k, v in flat if isinstance(v, str) and ("/" in v or "\\" in v)]
    real_paths = [v for v in path_values if Path(v).expanduser().exists()]
    if restrict_keys or real_paths:
        return True, f"{found.name} restricts paths ({len(restrict_keys)} path-ish keys, {len(real_paths)} real paths)"
    # fallback: any mcpServers with args containing a path token
    if "mcpServers" in text or "mcp_servers" in text:
        if re.search(r'"(args|command)"', text):
            return True, f"{found.name} present with server definitions"
    return False, f"{found.name} does not restrict paths"


def check_tdd_gate(root: Path):
    p = root / "scripts" / "tdd_gate.py"
    if not p.is_file():
        return False, "scripts/tdd_gate.py not found"
    text = read_text(p)
    if not is_substantive(text, 80):
        return False, "scripts/tdd_gate.py empty or placeholder-only"
    lower = text.lower()
    fail_closed = ("return 1" in text) and ("no test" in lower or "not found" in lower or "fail-closed" in lower or "fail closed" in lower)
    if not fail_closed:
        # still require return 1 somewhere
        fail_closed = "return 1" in text
    if not fail_closed:
        return False, "scripts/tdd_gate.py not fail-closed"
    # CI reference
    ci_refs = False
    wf_dir = root / ".github" / "workflows"
    if wf_dir.is_dir():
        for wf in wf_dir.glob("*.yml"):
            if "tdd_gate" in read_text(wf):
                ci_refs = True
        for wf in wf_dir.glob("*.yaml"):
            if "tdd_gate" in read_text(wf):
                ci_refs = True
    if not ci_refs:
        return False, "scripts/tdd_gate.py not referenced in CI"
    return True, "scripts/tdd_gate.py exists, fail-closed, referenced in CI"


def check_githooks(root: Path):
    hooks = [root / ".githooks" / "pre-commit", root / ".githooks" / "pre-push"]
    if not all(p.is_file() for p in hooks):
        return False, "missing .githooks/pre-commit or pre-push"
    for p in hooks:
        if not os.access(p, os.X_OK):
            return False, f"{p.name} not executable"
        if not is_substantive(read_text(p), 10):
            return False, f"{p.name} empty or placeholder-only"
    # installed via core.hooksPath
    installed = False
    try:
        res = subprocess.run(
            ["git", "-C", str(root), "config", "--get", "core.hooksPath"],
            capture_output=True, text=True, timeout=10,
        )
        val = res.stdout.strip()
        if val in (".githooks", "./.githooks") or val.endswith(".githooks"):
            installed = True
    except Exception:
        installed = True  # non-git environment: accept files
    if not installed:
        # also accept if .git/hooks has no copied hooks (not copied)
        return False, "core.hooksPath not set to .githooks"
    return True, ".githooks installed via core.hooksPath"


def check_evals(root: Path):
    d = root / "tests" / "evals"
    if not d.is_dir():
        return False, "tests/evals/ not found"
    eval_files = [f for f in d.rglob("*.py") if f.name != "__init__.py"]
    # also allow json/yaml ground truth with a test file
    gt_markers = ["ground_truth", "ground truth", "expected", "labels", "dataset"]
    substantive = []
    for f in eval_files:
        text = read_text(f)
        if not is_substantive(text, 40):
            continue
        lower = text.lower()
        has_gt = any(m in lower for m in gt_markers) or (d / "ground_truth.json").exists() or any(x.suffix in (".json", ".yaml", ".yml", ".csv") for x in d.iterdir() if x.is_file())
        if has_gt:
            substantive.append(f)
    if not eval_files:
        return False, "tests/evals/ has no eval test files"
    if not substantive:
        # accept any non-trivial eval file that references expected/assert
        for f in eval_files:
            text = read_text(f).lower()
            if "assert" in text or "expected" in text:
                substantive.append(f)
    if not substantive:
        return False, "tests/evals/ has no eval with ground truth"
    return True, f"{len(substantive)} eval(s) with ground truth"


def check_ci_evals(root: Path):
    wf_dir = root / ".github" / "workflows"
    if not wf_dir.is_dir():
        return False, "no .github/workflows/"
    found = False
    for wf in list(wf_dir.glob("*.yml")) + list(wf_dir.glob("*.yaml")):
        text = read_text(wf)
        if "eval" in text.lower() or "tests/evals" in text or "pytest" in text.lower():
            found = True
            break
    if not found:
        return False, "CI does not run evals/tests on PR"
    return True, "CI runs tests/evals on PR"


def check_telemetry(root: Path):
    candidates = [
        root / "scripts" / "hermes_telemetry.py",
        root / "scripts" / "telemetry.py",
    ]
    # search any telemetry script
    if not any(c.is_file() for c in candidates):
        for p in (root / "scripts").glob("*.py") if (root / "scripts").is_dir() else []:
            if "telemetry" in p.name.lower() or "metrics" in p.name.lower():
                candidates.append(p)
    found = None
    for c in candidates:
        if c.is_file():
            found = c
            break
    if found is None:
        # check workflows or src for telemetry emit
        for p in root.rglob("*.py"):
            if "telemetry" in read_text(p).lower() and ("emit" in read_text(p).lower() or "otlp" in read_text(p).lower() or "metric" in read_text(p).lower()):
                found = p
                break
    if found is None:
        return False, "no telemetry emitting metrics"
    text = read_text(found).lower()
    if not ("metric" in text or "otlp" in text or "emit" in text):
        return False, "telemetry script lacks metric emission"
    return True, f"telemetry emits metrics ({found})"


def check_no_llm_selfcert(root: Path):
    # AGENTS.md not LLM-generated
    agents = root / "AGENTS.md"
    if agents.is_file():
        text = read_text(agents).lower()
        if any(m in text for m in AUTO_GENERATED_MARKERS):
            return False, "AGENTS.md appears LLM-generated"
    # eval layer no self-certification
    eval_dir = root / "tests" / "evals"
    if eval_dir.is_dir():
        for f in eval_dir.rglob("*"):
            if not f.is_file():
                continue
            text = read_text(f).lower()
            if any(m in text for m in SELF_CERT_MARKERS):
                return False, f"model self-certification in {f}"
    # instruction files (CLAUDE.md etc.) not auto-generated
    for name in ("CLAUDE.md", "GEMINI.md", "COPILOT.md"):
        p = root / name
        if p.is_file():
            text = read_text(p).lower()
            if any(m in text for m in AUTO_GENERATED_MARKERS):
                return False, f"{name} appears LLM-generated"
    return True, "no LLM-generated instruction files or model self-certification"


ITEMS = [
    ("AGENTS.md lean/pointer-based", check_agents_md),
    (".agents/rules governance", check_rules),
    ("docs/PROJECT.md architecture", check_project_md),
    ("docs/TASKS.md roadmap", check_tasks_md),
    ("docs/adr/ present", check_adr),
    ("MCP config restricts paths", check_mcp),
    ("scripts/tdd_gate.py fail-closed+CI", check_tdd_gate),
    (".githooks installed", check_githooks),
    ("tests/evals/ with ground truth", check_evals),
    ("CI runs evals on PR", check_ci_evals),
    ("Telemetry emits metrics", check_telemetry),
    ("No LLM-generated/self-cert", check_no_llm_selfcert),
]


FRESHNESS_SLA_DAYS = 30
TIMESTAMP_FILE = ".audit_timestamp"

_TIMESTAMP_FORMATS = (
    "%Y-%m-%dT%H:%M:%S",
    "%Y-%m-%d %H:%M:%S",
    "%Y-%m-%d %H:%M",
    "%Y-%m-%d",
)


def read_audit_timestamp(root: Path):
    p = root / TIMESTAMP_FILE
    if not p.is_file():
        return None
    text = read_text(p).strip()
    if text:
        for fmt in _TIMESTAMP_FORMATS:
            try:
                return datetime.strptime(text, fmt)
            except ValueError:
                pass
        try:
            return datetime.fromtimestamp(float(text))
        except (ValueError, OSError, OverflowError):
            pass
    try:
        return datetime.fromtimestamp(p.stat().st_mtime)
    except Exception:
        return None


def check_freshness(root: Path):
    ts = read_audit_timestamp(root)
    now = datetime.now()
    if ts is None:
        return False, "no .audit_timestamp found; audit has never been run"
    age = now - ts
    if age > timedelta(days=FRESHNESS_SLA_DAYS):
        return False, f"audit stale: last run {ts.isoformat()} ({age.days} days ago; SLA {FRESHNESS_SLA_DAYS} days)"
    return True, f"audit fresh: last run {ts.isoformat()} ({age.days} days ago)"


def write_audit_timestamp(root: Path):
    p = root / TIMESTAMP_FILE
    try:
        p.write_text(datetime.now().isoformat(timespec="seconds"), encoding="utf-8")
    except Exception:
        pass


def audit(root: Path):
    results = []
    for idx, (name, fn) in enumerate(ITEMS, start=1):
        passed, evidence = fn(root)
        results.append({
            "id": idx,
            "name": name,
            "passed": bool(passed),
            "evidence": evidence,
        })
    score = sum(1 for r in results if r["passed"])
    return {
        "project": str(root.resolve()),
        "score": score,
        "total": len(results),
        "production_grade": score >= 10,
        "items": results,
    }


def print_scorecard(data):
    print(f"5-Layer Audit Scorecard: {data['project']}")
    print("=" * 70)
    for item in data["items"]:
        status = "PASS" if item["passed"] else "FAIL"
        mark = "✅" if item["passed"] else "❌"
        print(f"{mark} [{item['id']:>2}/12] {item['name']}: {status} — {item['evidence']}")
    print("=" * 70)
    print(f"Score: {data['score']}/{data['total']}")
    print(f"Production-grade (>=10): {'yes' if data['production_grade'] else 'no'}")


def main():
    parser = argparse.ArgumentParser(description="Audit project against 5-layer architecture checklist")
    parser.add_argument("project", nargs="?", default=".", help="project directory (default: cwd)")
    parser.add_argument("--json", action="store_true", help="machine-readable JSON output")
    parser.add_argument("--freshness", action="store_true", help="check freshness SLA: warn if audit older than 30 days")
    args = parser.parse_args()

    root = Path(args.project).resolve()
    if not root.is_dir():
        print(f"Project directory not found: {root}", file=sys.stderr)
        sys.exit(2)

    # freshness check before audit
    freshness_passed = None
    freshness_msg = None
    if args.freshness:
        freshness_passed, freshness_msg = check_freshness(root)

    data = audit(root)

    # write timestamp after audit
    write_audit_timestamp(root)

    if args.freshness:
        freshness_json = {
            "passed": freshness_passed,
            "message": freshness_msg,
        }
        # include in JSON output
        data["freshness"] = freshness_json
        if not freshness_passed:
            print(f"Warning: {freshness_msg}", file=sys.stderr)
            if args.json:
                pass  # JSON mode: warning already on stderr below
            else:
                print(f"Warning: {freshness_msg}")

    if args.json:
        print(json.dumps(data, indent=2))
    else:
        print_scorecard(data)
        if not freshness_passed:
            print(f"Warning: {freshness_msg}", file=sys.stderr)
    sys.exit(0)


if __name__ == "__main__":
    main()
